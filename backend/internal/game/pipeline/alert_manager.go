// NewAlertManager creates a new alert manager
func NewAlertManager(projectRoot string, config AlertConfig) *AlertManager {
	alertsFile := filepath.Join(projectRoot, "benchmarks", "alerts", "history.json")

	// Ensure alerts directory exists
	os.MkdirAll(filepath.Dir(alertsFile), 0755)

	return &AlertManager{
		config:      config,
		projectRoot: projectRoot,
		alertsFile:  alertsFile,
	}
}

// ProcessAlerts processes regression analysis and sends appropriate alerts
func (am *AlertManager) ProcessAlerts(analysis *RegressionAnalysis) error {
	if !am.config.Enabled {
		return nil
	}

	// Load alert history for rate limiting
	history, err := am.loadAlertHistory()
	if err != nil {
		history = &AlertHistory{Alerts: make([]SentAlert, 0)}
	}

	// Process individual alerts
	for _, alert := range analysis.Alerts {
		if am.shouldSendAlert(alert, history) {
			if err := am.sendAlert(alert, analysis); err != nil {
				fmt.Printf("Failed to send alert: %v\n", err)
				continue
			}

			// Record sent alert
			sentAlert := SentAlert{
				ID:        am.generateAlertID(alert),
				Type:      alert.Type,
				Severity:  alert.Severity,
				Benchmark: alert.BenchmarkName,
				Timestamp: time.Now(),
				Hash:      am.calculateAlertHash(alert),
			}
			history.Alerts = append(history.Alerts, sentAlert)
		}
	}

	// Send summary alert if there are significant regressions
	if am.shouldSendSummaryAlert(analysis) {
		if err := am.sendSummaryAlert(analysis); err != nil {
			fmt.Printf("Failed to send summary alert: %v\n", err)
		}
	}

	// Clean up old alerts and save history
	am.cleanupAlertHistory(history)
	return am.saveAlertHistory(history)
}

// shouldSendAlert determines if an alert should be sent based on configuration and rate limiting
func (am *AlertManager) shouldSendAlert(alert RegressionAlert, history *AlertHistory) bool {
	// Check if alert type is enabled
	switch alert.Type {
	case "performance":
		switch alert.Severity {
		case "minor":
			if !am.config.AlertThresholds.MinorDegradation {
				return false
			}
		case "major":
			if !am.config.AlertThresholds.MajorDegradation {
				return false
			}
		case "critical":
			if !am.config.AlertThresholds.CriticalDegradation {
				return false
			}
		}
	case "variance":
		if !am.config.AlertThresholds.HighVariance {
			return false
		}
	case "trend":
		if !am.config.AlertThresholds.TrendDegradation {
			return false
		}
	}

	// Check rate limiting
	if am.isRateLimited(history) {
		return false
	}

	// Check for duplicate alerts
	if am.config.RateLimiting.SuppressRepeated {
		alertHash := am.calculateAlertHash(alert)
		cutoff := time.Now().Add(-am.config.RateLimiting.DuplicateWindow)

		for _, sent := range history.Alerts {
			if sent.Hash == alertHash && sent.Timestamp.After(cutoff) {
				return false // Duplicate alert within window
			}
		}
	}

	return true
}

// shouldSendSummaryAlert determines if a summary alert should be sent
func (am *AlertManager) shouldSendSummaryAlert(analysis *RegressionAnalysis) bool {
	return analysis.Summary.CriticalRegressions > 0 ||
		analysis.Summary.MajorRegressions > 2 ||
		analysis.Summary.AlertsGenerated > 5
}

// sendAlert sends an individual alert through configured channels
func (am *AlertManager) sendAlert(alert RegressionAlert, analysis *RegressionAnalysis) error {
	for _, channel := range am.config.NotificationChannels {
		if !channel.Enabled {
			continue
		}

		// Check if this channel should receive this severity
		shouldSend := false
		for _, priority := range channel.Priority {
			if priority == alert.Severity {
				shouldSend = true
				break
			}
		}

		if !shouldSend {
			continue
		}

		switch channel.Type {
		case "github":
			err := am.sendGitHubAlert(alert, analysis, channel)
			if err != nil {
				return fmt.Errorf("GitHub alert failed: %v", err)
			}
		case "slack":
			err := am.sendSlackAlert(alert, analysis, channel)
			if err != nil {
				return fmt.Errorf("Slack alert failed: %v", err)
			}
		case "webhook":
			err := am.sendWebhookAlert(alert, analysis, channel)
			if err != nil {
				return fmt.Errorf("Webhook alert failed: %v", err)
			}
		}
	}

	return nil
}


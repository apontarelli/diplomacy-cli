// sendSlackAlert sends an alert to Slack
func (am *AlertManager) sendSlackAlert(alert RegressionAlert, analysis *RegressionAnalysis, channel NotificationChannel) error {
	webhookURL := channel.Config["webhook_url"]
	if webhookURL == "" {
		return fmt.Errorf("Slack webhook URL not configured")
	}

	// Format message for Slack
	message := am.formatSlackMessage(alert, analysis)

	payload := map[string]interface{}{
		"text": message,
		"attachments": []map[string]interface{}{
			{
				"color": am.getSlackColor(alert.Severity),
				"fields": []map[string]interface{}{
					{
						"title": "Benchmark",
						"value": alert.BenchmarkName,
						"short": true,
					},
					{
						"title": "Severity",
						"value": strings.ToUpper(alert.Severity),
						"short": true,
					},
				},
			},
		},
	}

	return am.sendWebhookPayload(webhookURL, payload)
}

// sendWebhookAlert sends a generic webhook alert
func (am *AlertManager) sendWebhookAlert(alert RegressionAlert, analysis *RegressionAnalysis, channel NotificationChannel) error {
	webhookURL := channel.Config["url"]
	if webhookURL == "" {
		return fmt.Errorf("Webhook URL not configured")
	}

	payload := map[string]interface{}{
		"alert":     alert,
		"analysis":  analysis,
		"timestamp": time.Now(),
	}

	return am.sendWebhookPayload(webhookURL, payload)
}

// sendSummaryAlert sends a summary of all alerts
func (am *AlertManager) sendSummaryAlert(analysis *RegressionAnalysis) error {
	// Create summary alert
	summaryAlert := RegressionAlert{
		Type:      "summary",
		Severity:  "major",
		Message:   am.formatSummaryMessage(analysis),
		Timestamp: time.Now(),
	}

	return am.sendAlert(summaryAlert, analysis)
}

// Helper methods

func (am *AlertManager) generateAlertID(alert RegressionAlert) string {
	return fmt.Sprintf("%s_%s_%s_%d",
		alert.Type, alert.BenchmarkName, alert.Severity, alert.Timestamp.Unix())
}

func (am *AlertManager) calculateAlertHash(alert RegressionAlert) string {
	// Simple hash for duplicate detection
	return fmt.Sprintf("%s_%s_%s", alert.Type, alert.BenchmarkName, alert.Severity)
}

func (am *AlertManager) isRateLimited(history *AlertHistory) bool {
	cutoff := time.Now().Add(-time.Hour)
	count := 0

	for _, alert := range history.Alerts {
		if alert.Timestamp.After(cutoff) {
			count++
		}
	}

	return count >= am.config.RateLimiting.MaxAlertsPerHour
}

func (am *AlertManager) formatSlackMessage(alert RegressionAlert, analysis *RegressionAnalysis) string {
	emoji := "⚠️"
	if alert.Severity == "critical" {
		emoji = "🚨"
	}

	return fmt.Sprintf("%s Performance Alert: %s\n%s", emoji, alert.BenchmarkName, alert.Message)
}

func (am *AlertManager) formatSummaryMessage(analysis *RegressionAnalysis) string {
	return fmt.Sprintf("Performance regression summary: %d total regressions (%d critical, %d major)",
		analysis.Summary.CriticalRegressions+analysis.Summary.MajorRegressions+analysis.Summary.MinorRegressions,
		analysis.Summary.CriticalRegressions,
		analysis.Summary.MajorRegressions)
}

func (am *AlertManager) getSlackColor(severity string) string {
	switch severity {
	case "critical":
		return "danger"
	case "major":
		return "warning"
	default:
		return "good"
	}
}

func (am *AlertManager) sendWebhookPayload(url string, payload interface{}) error {
	data, err := json.Marshal(payload)
	if err != nil {
		return err
	}

	resp, err := http.Post(url, "application/json", bytes.NewBuffer(data))
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 400 {
		body, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("webhook failed with status %d: %s", resp.StatusCode, string(body))
	}

	return nil
}

func (am *AlertManager) loadAlertHistory() (*AlertHistory, error) {
	data, err := os.ReadFile(am.alertsFile)
	if err != nil {
		return nil, err
	}

	var history AlertHistory
	err = json.Unmarshal(data, &history)
	return &history, err
}

func (am *AlertManager) saveAlertHistory(history *AlertHistory) error {
	data, err := json.MarshalIndent(history, "", "  ")
	if err != nil {
		return err
	}

	return os.WriteFile(am.alertsFile, data, 0644)
}

func (am *AlertManager) cleanupAlertHistory(history *AlertHistory) {
	// Remove alerts older than 30 days
	cutoff := time.Now().AddDate(0, 0, -30)
	filtered := make([]SentAlert, 0)

	for _, alert := range history.Alerts {
		if alert.Timestamp.After(cutoff) {
			filtered = append(filtered, alert)
		}
	}

	history.Alerts = filtered
}
